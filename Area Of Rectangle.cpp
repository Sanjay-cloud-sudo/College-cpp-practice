// Area Of Rectangle
#include <iostream>
using namespace std;
int main() 
{
    int length,breadth;
    cout<<"Enter Length of Rectangle"<<endl;
    cin>>length;
    cout<<"Enter Breadth of Rectangle"<<endl;
    cin>>breadth;
    int area=length*breadth;
    cout<<"Area Of Rectangle is "<<area;
    return 0;
}
